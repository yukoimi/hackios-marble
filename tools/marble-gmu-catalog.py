#!/usr/bin/env python3
"""Export the pinned Mu-marble DT catalog for CPU-only Gen7 table planning.

These are DT candidate levels, not a speed-bin/OPP enable decision.
"""
import argparse
import hashlib
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--dt', type=Path, default=Path('../image-inspection/marble-dtb.json'))
parser.add_argument('--provenance', type=Path, default=Path('../marble-baselines/20261024-gmu-preflight/marble-gmu-preflight-source-provenance.json'))
parser.add_argument('--output', type=Path, required=True)
args = parser.parse_args()
raw = args.dt.read_bytes()
digest = hashlib.sha256(raw).hexdigest()
if digest != json.loads(args.provenance.read_text())['dt_sha256']:
    raise ValueError('DT differs from passed board provenance')
dt = json.loads(raw)
base = '/soc/qcom,kgsl-3d0@3d00000'
gpu = dt[base]
assert gpu['qcom,chipid'] == ['0x7030002']
levels = []
for i in range(7):
    node = dt[base + '/qcom,gpu-pwrlevels/qcom,gpu-pwrlevel@' + str(i)]
    assert int(node['reg'][0], 0) == i
    levels.append([int(node[key][0], 0) for key in ('qcom,gpu-freq', 'qcom,level', 'qcom,cx-level')])
ddr = [int(x, 0) for x in gpu['qcom,bus-table-ddr']]
cnoc = [int(x, 0) for x in gpu['qcom,bus-table-cnoc']]
assert cnoc == [0, 100] and len(ddr) == 12 and len(levels) == 7
text = ['/* Generated by marble-gmu-catalog.py from Mu-marble DT. CPU-only candidates.',
        ' * DT SHA256: ' + digest,
        ' * No speed-bin/OPP policy, voltage or bandwidth request is authorized. */',
        '#ifndef MARBLE_GMU_CATALOG_H\n#define MARBLE_GMU_CATALOG_H\n#include <stdint.h>',
        'typedef struct {uint32_t hz,level,cx_level;} MarbleGmuCatalogLevel;',
        'static const MarbleGmuCatalogLevel marble_gmu_gpu_candidates[7]={']
text += ['    {' + ','.join(str(x) for x in row) + '},' for row in reversed(levels)]
text += ['};', 'static const uint32_t marble_gmu_ddr_candidates[12]={' + ','.join(map(str, ddr)) + '};',
         '#endif']
args.output.write_text('\n'.join(text) + '\n')
print(args.output)
